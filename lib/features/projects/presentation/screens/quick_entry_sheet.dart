import 'project_detail_screen.dart';

class QuickEntrySheet extends ConsumerStatefulWidget {
  final String projectId;
  final String? workshopId;
  final VoidCallback? onUnitAdded;

  const QuickEntrySheet({
    super.key,
    required this.projectId,
    this.workshopId,
    this.onUnitAdded,
  });

  @override
  ConsumerState<QuickEntrySheet> createState() => _QuickEntrySheetState();
}

class _QuickEntrySheetState extends ConsumerState<QuickEntrySheet> {
  final _nameController = TextEditingController();
  final _widthController = TextEditingController(text: '0');
  final _heightController = TextEditingController(text: '0');
  final _locationController = TextEditingController();
  int _quantity = 1;
  String _unitType = 'window';
  bool _isSaving = false;
  bool _showCustomOverrides = false;
  final Map<String, dynamic> _overrides = {};
  bool _didInitName = false;

  @override
  void dispose() {
    _nameController.dispose();
    _widthController.dispose();
    _heightController.dispose();
    _locationController.dispose();
    super.dispose();
  }

  String _resolveWorkshopId() {
    final activeId = ref.read(activeWorkshopIdProvider);
    final currentUser = ref.read(currentUserProvider).value;
    return (widget.workshopId != null && widget.workshopId!.isNotEmpty)
        ? widget.workshopId!
        : (activeId ?? (currentUser?.workshopId ?? ''));
  }

  void _syncAutoName(List<ProjectUnit> units, {bool force = false}) {
    if (force ||
        !_didInitName ||
        ProjectUnit.isAutoGeneratedName(_nameController.text)) {
      _nameController.text = ProjectUnit.nextAutoName(_unitType, units);
      _didInitName = true;
    }
  }

  void _resetForNextItem(List<ProjectUnit> updatedUnits) {
    _widthController.text = '0';
    _heightController.text = '0';
    _locationController.clear();
    setState(() {
      _quantity = 1;
      _overrides.clear();
      _showCustomOverrides = false;
      _nameController.text = ProjectUnit.nextAutoName(_unitType, updatedUnits);
    });
  }

  Future<void> _submit(
    ProjectDefaults projectDefaults,
    List<ProjectUnit> existingUnits,
  ) async {
    final width = double.tryParse(_widthController.text.trim());
    final height = double.tryParse(_heightController.text.trim());
    final location = _locationController.text.trim();
    final rawName = _nameController.text.trim();
    final name = rawName.isEmpty
        ? ProjectUnit.nextAutoName(_unitType, existingUnits)
        : rawName;

    if (width == null || width <= 0) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('يرجى إدخال عرض صحيح أكبر من صفر')),
      );
      return;
    }

    if (height == null || height <= 0) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('يرجى إدخال ارتفاع صحيح أكبر من صفر')),
      );
      return;
    }

    final workshopId = _resolveWorkshopId();
    if (workshopId.isEmpty) return;

    final workshopRules = ref.read(effectiveRulesProvider(workshopId)).value ??
        SeedRules.getSystem2000BeadedRules();
    final effectiveRules = ProjectUnit.resolveEffectiveRules(
      workshopRules,
      projectDefaults: projectDefaults,
    );
    final engine = CalculatorEngine(rules: effectiveRules);

    final effectiveGlazing = _overrides['glazingMode'] as String? ??
        projectDefaults.glazingMode;
    final effectiveColor =
        _overrides['color'] as String? ?? projectDefaults.color;
    final effectiveGlassType =
        _overrides['glassType'] as String? ?? projectDefaults.glassType;
    final effectiveGlassThickness =
        (_overrides['glassThicknessMm'] as num?)?.toDouble() ??
            projectDefaults.glassThicknessMm;
    final effectiveHasGasket =
        _overrides['hasGasket'] as bool? ?? projectDefaults.hasGasket;

    final spec = UnitSpecification(
      widthCm: width,
      heightCm: height,
      quantity: _quantity,
      unitType: _unitType,
      glazingMode: effectiveGlazing,
      profileSystemId: projectDefaults.profileSystemId,
      glassType: effectiveGlassType,
      glassThicknessMm: effectiveGlassThickness,
      hasGasket: effectiveHasGasket,
      customOptions: {'color': effectiveColor},
    );
    final calc = engine.calculate(spec);
    if (!calc.isValid) {
      final firstIssue = calc.issues.isNotEmpty
          ? calc.issues.first.message
          : 'الأبعاد غير مطابقة لقواعد التصنيع';
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text(
            'القياس غير صالح للتصنيع: $firstIssue\n(الحد الأدنى: العرض > 16.2 سم، الارتفاع > 14 سم)',
          ),
          backgroundColor: AppColors.error,
          duration: const Duration(seconds: 4),
        ),
      );
      return;
    }

    setState(() => _isSaving = true);

    try {
      final unit = ProjectUnit(
        id: '',
        projectId: widget.projectId,
        name: name,
        location: location,
        widthCm: width,
        heightCm: height,
        quantity: _quantity,
        unitType: _unitType,
        glazingMode: effectiveGlazing,
        profileSystemId: projectDefaults.profileSystemId,
        color: effectiveColor,
        glassType: effectiveGlassType,
        glassThicknessMm: effectiveGlassThickness,
        hasGasket: effectiveHasGasket,
        ruleVersionIdsUsed: calc.ruleVersionIdsUsed,
        overrides: Map<String, dynamic>.from(_overrides),
        createdAt: DateTime.now(),
        updatedAt: DateTime.now(),
      );

      await ref.read(projectsRepositoryProvider).saveUnit(workshopId, unit);
      widget.onUnitAdded?.call();

      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('تمت إضافة "$name" بنجاح'),
            backgroundColor: AppColors.success,
            duration: const Duration(seconds: 2),
          ),
        );
        _resetForNextItem([...existingUnits, unit]);
      }
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('حدث خطأ أثناء الحفظ: $e'),
            backgroundColor: AppColors.error,
          ),
        );
      }
    } finally {
      if (mounted) setState(() => _isSaving = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;
    final workshopId = _resolveWorkshopId();
    final query = (workshopId: workshopId, projectId: widget.projectId);
    final project = ref.watch(projectDetailProvider(query)).value;
    final existingUnits =
        ref.watch(projectUnitsProvider(query)).value ?? const [];
    final defaults = project?.defaults ?? const ProjectDefaults();

    if (!_didInitName) {
      _syncAutoName(existingUnits);
    }

    return Directionality(
      textDirection: TextDirection.rtl,
      child: SingleChildScrollView(
        padding: EdgeInsets.only(
          left: 20,
          right: 20,
          top: 20,
          bottom: MediaQuery.of(context).viewInsets.bottom + 24,
        ),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: [
                Row(
                  children: [
                    const Icon(
                      Icons.flash_on_rounded,
                      color: AppColors.amberPrimary,
                    ),
                    const SizedBox(width: 8),
                    Text(
                      'إدخال قياسات سريع',
                      style: theme.textTheme.titleMedium?.copyWith(
                        fontWeight: FontWeight.w800,
                      ),
                    ),
                  ],
                ),
                IconButton(
                  icon: const Icon(Icons.close_rounded),
                  onPressed: () => Navigator.of(context).pop(),
                ),
              ],
            ),
            const SizedBox(height: 12),

            // Unit Type Selector First so name auto-updates ("شباك 1" vs "واجهة 1")
            SegmentedButton<String>(
              segments: const [
                ButtonSegment<String>(
                  value: 'window',
                  label: Text('شباك نافذة'),
                  icon: Icon(Icons.window_rounded, size: 18),
                ),
                ButtonSegment<String>(
                  value: 'facade',
                  label: Text('واجهة زجاجية'),
                  icon: Icon(Icons.apartment_rounded, size: 18),
                ),
              ],
              selected: {_unitType},
              onSelectionChanged: (newSelection) {
                setState(() {
                  _unitType = newSelection.first;
                  if (ProjectUnit.isAutoGeneratedName(_nameController.text)) {
                    _nameController.text =
                        ProjectUnit.nextAutoName(_unitType, existingUnits);
                  }
                });
              },
            ),

            const SizedBox(height: 14),

            // Name and Location
            Row(
              children: [
                Expanded(
                  flex: 3,
                  child: TextField(
                    controller: _nameController,
                    decoration: const InputDecoration(
                      labelText: 'اسم العنصر *',
                      hintText: 'مثال: شباك 1',
                    ),
                  ),
                ),
                const SizedBox(width: 10),
                Expanded(
                  flex: 2,
                  child: TextField(
                    controller: _locationController,
                    decoration: const InputDecoration(
                      labelText: 'المكان',
                      hintText: 'مثال: الدور 1',
                    ),
                  ),
                ),
              ],
            ),

            const SizedBox(height: 12),

            // Width (starts at 0), Height (starts at 0), Quantity
            Row(
              children: [
                Expanded(
                  flex: 4,
                  child: TextField(
                    controller: _widthController,
                    autofocus: true,
                    keyboardType:
                        const TextInputType.numberWithOptions(decimal: true),
                    onTap: () {
                      if (_widthController.text == '0') {
                        _widthController.selection = TextSelection(
                          baseOffset: 0,
                          extentOffset: _widthController.text.length,
                        );
                      }
                    },
                    decoration: const InputDecoration(
                      labelText: 'العرض (سم) *',
                      suffixText: 'سم',
                      contentPadding:
                          EdgeInsets.symmetric(horizontal: 10, vertical: 12),
                    ),
                  ),
                ),
                const SizedBox(width: 8),
                Expanded(
                  flex: 4,
                  child: TextField(
                    controller: _heightController,
                    keyboardType:
                        const TextInputType.numberWithOptions(decimal: true),
                    onTap: () {
                      if (_heightController.text == '0') {
                        _heightController.selection = TextSelection(
                          baseOffset: 0,
                          extentOffset: _heightController.text.length,
                        );
                      }
                    },
                    decoration: const InputDecoration(
                      labelText: 'الارتفاع (سم) *',
                      suffixText: 'سم',
                      contentPadding:
                          EdgeInsets.symmetric(horizontal: 10, vertical: 12),
                    ),
                  ),
                ),
                const SizedBox(width: 8),
                Expanded(
                  flex: 3,
                  child: DropdownButtonFormField<int>(
                    isExpanded: true,
                    initialValue: _quantity,
                    decoration: const InputDecoration(
                      labelText: 'العدد',
                      contentPadding:
                          EdgeInsets.symmetric(horizontal: 8, vertical: 8),
                    ),
                    items: List.generate(20, (i) => i + 1)
                        .map(
                          (q) => DropdownMenuItem(value: q, child: Text('$q')),
                        )
                        .toList(),
                    onChanged: (val) {
                      if (val != null) setState(() => _quantity = val);
                    },
                  ),
                ),
              ],
            ),

            const SizedBox(height: 12),

            // Inherited General Project Properties Summary + Optional Per-Item Override
            Container(
              padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 10),
              decoration: BoxDecoration(
                color: isDark ? AppColors.darkCard : AppColors.lightSurface,
                borderRadius: BorderRadius.circular(12),
                border: Border.all(
                  color: _overrides.isNotEmpty
                      ? AppColors.amberPrimary
                      : (isDark ? AppColors.darkBorder : AppColors.lightBorder),
                ),
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Row(
                    children: [
                      Icon(
                        _overrides.isNotEmpty
                            ? Icons.edit_note_rounded
                            : Icons.check_circle_outline_rounded,
                        size: 18,
                        color: _overrides.isNotEmpty
                            ? AppColors.amberPrimary
                            : AppColors.success,
                      ),
                      const SizedBox(width: 6),
                      Expanded(
                        child: Text(
                          _overrides.isNotEmpty
                              ? 'خصائص مخصصة لهذا العنصر (${_overrides.length})'
                              : 'يرث الخصائص العامة للمشروع (${ProjectDefaults.glazingModeLabelAr(defaults.glazingMode)} • ${ProjectDefaults.colorLabelAr(defaults.color)} • ${ProjectDefaults.glassTypeLabelAr(defaults.glassType)} ${defaults.glassThicknessMm.toInt()} ملم)',
                          style: const TextStyle(
                            fontSize: 12,
                            fontWeight: FontWeight.w600,
                          ),
                        ),
                      ),
                      if (_overrides.isNotEmpty)
                        TextButton.icon(
                          onPressed: () => setState(_overrides.clear),
                          icon: const Icon(Icons.restore_rounded, size: 15),
                          label: const Text(
                            'استرجاع الافتراضي',
                            style: TextStyle(fontSize: 11),
                          ),
                        ),
                      TextButton(
                        onPressed: () => setState(
                          () => _showCustomOverrides = !_showCustomOverrides,
                        ),
                        child: Text(
                          _showCustomOverrides ? 'إخفاء' : 'تخصيص ✎',
                          style: const TextStyle(
                            fontSize: 12,
                            fontWeight: FontWeight.w700,
                          ),
                        ),
                      ),
                    ],
                  ),
                  if (_showCustomOverrides) ...[
                    const Divider(height: 16),
                    Row(
                      children: [
                        Expanded(
                          child: DropdownButtonFormField<String>(
                            isExpanded: true,
                            initialValue: _overrides['glazingMode'] as String? ??
                                defaults.glazingMode,
                            decoration: const InputDecoration(
                              labelText: 'ألمنيوم العنصر',
                              isDense: true,
                            ),
                            items: const [
                              DropdownMenuItem(
                                value: 'double',
                                child: Text('دبل'),
                              ),
                              DropdownMenuItem(
                                value: 'single',
                                child: Text('عادي (مفرد)'),
                              ),
                            ],
                            onChanged: (val) {
                              if (val != null) {
                                setState(() {
                                  if (val == defaults.glazingMode) {
                                    _overrides.remove('glazingMode');
                                  } else {
                                    _overrides['glazingMode'] = val;
                                  }
                                });
                              }
                            },
                          ),
                        ),
                        const SizedBox(width: 8),
                        Expanded(
                          child: DropdownButtonFormField<String>(
                            isExpanded: true,
                            initialValue: _overrides['color'] as String? ??
                                defaults.color,
                            decoration: const InputDecoration(
                              labelText: 'لون العنصر',
                              isDense: true,
                            ),
                            items: ProjectGeneralPropertiesCard.colorOptions
                                .map(
                                  (c) => DropdownMenuItem(
                                    value: c.value,
                                    child: Text(c.label),
                                  ),
                                )
                                .toList(),
                            onChanged: (val) {
                              if (val != null) {
                                setState(() {
                                  if (val == defaults.color) {
                                    _overrides.remove('color');
                                  } else {
                                    _overrides['color'] = val;
                                  }
                                });
                              }
                            },
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 10),
                    Row(
                      children: [
                        Expanded(
                          child: DropdownButtonFormField<String>(
                            isExpanded: true,
                            initialValue: _overrides['glassType'] as String? ??
                                defaults.glassType,
                            decoration: const InputDecoration(
                              labelText: 'نوع الزجاج',
                              isDense: true,
                            ),
                            items: ProjectGeneralPropertiesCard.glassTypeOptions
                                .map(
                                  (g) => DropdownMenuItem(
                                    value: g.value,
                                    child: Text(g.label),
                                  ),
                                )
                                .toList(),
                            onChanged: (val) {
                              if (val != null) {
                                setState(() {
                                  if (val == defaults.glassType) {
                                    _overrides.remove('glassType');
                                  } else {
                                    _overrides['glassType'] = val;
                                  }
                                });
                              }
                            },
                          ),
                        ),
                        const SizedBox(width: 8),
                        Expanded(
                          child: DropdownButtonFormField<double>(
                            isExpanded: true,
                            initialValue: (_overrides['glassThicknessMm'] as num?)
                                    ?.toDouble() ??
                                defaults.glassThicknessMm,
                            decoration: const InputDecoration(
                              labelText: 'سماكة الزجاج',
                              isDense: true,
                            ),
                            items: ProjectGeneralPropertiesCard
                                .glassThicknessOptions
                                .map(
                                  (t) => DropdownMenuItem(
                                    value: t.value,
                                    child: Text(t.label),
                                  ),
                                )
                                .toList(),
                            onChanged: (val) {
                              if (val != null) {
                                setState(() {
                                  if (val == defaults.glassThicknessMm) {
                                    _overrides.remove('glassThicknessMm');
                                  } else {
                                    _overrides['glassThicknessMm'] = val;
                                  }
                                });
                              }
                            },
                          ),
                        ),
                      ],
                    ),
                    const SizedBox(height: 10),
                    DropdownButtonFormField<bool>(
                      isExpanded: true,
                      initialValue: _overrides['hasGasket'] as bool? ??
                          defaults.hasGasket,
                      decoration: const InputDecoration(
                        labelText: 'كوتشوك الزجاج لهذا العنصر',
                        isDense: true,
                      ),
                      items: const [
                        DropdownMenuItem(
                          value: false,
                          child: Text('لا · لا تضف الكوتشوك للطلبية'),
                        ),
                        DropdownMenuItem(
                          value: true,
                          child: Text('نعم · أضف الكوتشوك للطلبية'),
                        ),
                      ],
                      onChanged: (val) {
                        if (val != null) {
                          setState(() {
                            if (val == defaults.hasGasket) {
                              _overrides.remove('hasGasket');
                            } else {
                              _overrides['hasGasket'] = val;
                            }
                          });
                        }
                      },
                    ),
                  ],
                ],
              ),
            ),

            const SizedBox(height: 16),

            ElevatedButton.icon(
              icon: _isSaving
                  ? const SizedBox(
                      width: 18,
                      height: 18,
                      child: CircularProgressIndicator(strokeWidth: 2),
                    )
                  : const Icon(Icons.add_rounded),
              label: const Text('إضافة العنصر والمتابعة'),
              onPressed: _isSaving
                  ? null
                  : () => _submit(defaults, existingUnits),
            ),
          ],
        ),
      ),
    );
  }
}
